"""Write docs/diagrams/er-diagram.dot from the SQLAlchemy models.

The diagram is generated from the same metadata Alembic uses, so it cannot
drift from the real schema. From the repository root:

    PYTHONPATH=backend python docs/diagrams/er_diagram.py
    dot -Tpng -Gdpi=110 docs/diagrams/er-diagram.dot -o docs/er-diagram.png
"""

from html import escape
from pathlib import Path

from sqlalchemy import Column, Table

from app.models import Base

OUTPUT = Path(__file__).with_name("er-diagram.dot")
# Present on every table; listed once in the caption instead of 13 times.
COMMON = {"created_at", "updated_at"}


def column_row(column: Column) -> str:
    marks = []
    if column.primary_key:
        marks.append("PK")
    if column.foreign_keys:
        marks.append("FK")
    single = [i for i in column.table.indexes if i.unique and list(i.columns) == [column]]
    if column.unique or any(i.dialect_options["postgresql"]["where"] is None for i in single):
        marks.append("UQ")
    elif single:
        # Partial unique index, e.g. one open loan per device.
        marks.append("UQ*")
    name = escape(column.name)
    if column.primary_key:
        name = f"<B>{name}</B>"
    kind = escape(str(column.type).split("(")[0].lower())
    # Graphviz rejects an empty FONT element, so the cell stays blank instead.
    keys = f'<FONT COLOR="#1f5fa8">{" ".join(marks)}</FONT>' if marks else " "
    return (
        f'<TR><TD ALIGN="LEFT" PORT="{column.name}">{name}</TD>'
        f'<TD ALIGN="LEFT"><FONT COLOR="#555555">{kind}</FONT></TD>'
        f'<TD ALIGN="LEFT">{keys}</TD></TR>'
    )


def table_node(table: Table) -> str:
    rows = "".join(column_row(c) for c in table.columns if c.name not in COMMON)
    return (
        f"  {table.name} [label=<"
        '<TABLE BORDER="0" CELLBORDER="1" CELLSPACING="0" CELLPADDING="4">'
        f'<TR><TD COLSPAN="3" BGCOLOR="#dde8f5"><B>{table.name}</B></TD></TR>'
        f"{rows}</TABLE>>];"
    )


def main() -> None:
    tables = Base.metadata.sorted_tables
    lines = [
        "// Generated by er_diagram.py from the SQLAlchemy models. Do not edit by hand.",
        "digraph er {",
        '  graph [rankdir=LR, fontname="Helvetica", fontsize=11, nodesep=0.4, ranksep=0.9,',
        '         labelloc=b, label="Every table also has created_at and updated_at. '
        'PK primary key, FK foreign key, UQ unique, '
        'UQ* unique among matching rows only (one open loan per device)."];',
        '  node [shape=plain, fontname="Helvetica", fontsize=10];',
        '  edge [fontname="Helvetica", fontsize=9, color="#666666", arrowhead=crow,'
        " arrowtail=tee, dir=both];",
    ]
    lines += [table_node(t) for t in tables]
    for table in tables:
        for column in table.columns:
            for fk in column.foreign_keys:
                target = fk.column.table.name
                lines.append(
                    f"  {target}:{fk.column.name} -> {table.name}:{column.name}"
                    f' [label="{column.name}"];'
                )
    lines.append("}")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
